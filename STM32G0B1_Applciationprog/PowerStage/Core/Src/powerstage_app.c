/*
 * powerstage_app.c
 *
 *  Created on: 15 Mar 2026
 *      Author: jordan
 *
 *  Application state machine — Init → Running ↔ Fault
 *
 *  State descriptions:
 *
 *    INIT
 *      Runs once on the very first PS_App_Task() call.
 *      Probes I2C devices (EEPROM, OLED), loads/defaults config,
 *      initialises all sub-modules, starts ADC DMA, shows splash screen.
 *      Unconditionally transitions to RUNNING when complete.
 *
 *    RUNNING
 *      Normal operation at two periodic rates:
 *        MEASURE_INTERVAL_MS  — ADC readings, OC check, UV check
 *        BROADCAST_INTERVAL_MS — CAN broadcast of all status frames
 *      Also handles pending CAN RX commands every cycle.
 *      Transitions to FAULT when any ERR_xxx bit appears in error_code.
 *
 *    FAULT
 *      Same measurement and CAN handling as RUNNING, but:
 *        - UI state shown as SYS_FAULT (display cycles to fault page)
 *        - CAN broadcasts only state + voltage (minimal)
 *      Returns to RUNNING when all ERR_xxx bits are cleared.
 */

